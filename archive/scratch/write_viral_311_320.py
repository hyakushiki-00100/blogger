def omake(items):
    parts = []
    for idx, (label, text) in enumerate(items):
        num = ["①", "②", "③"][idx]
        sep = "<br><br>" if idx < len(items) - 1 else ""
        parts.append(f"<b>{num} {label}：</b> {text}{sep}")
    return OMAKE_HEADER + "".join(parts)

